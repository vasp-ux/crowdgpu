"""
User ORM model.

Represents a CrowdGPU platform user (consumer or provider).

Authentication credentials are NOT stored here — that belongs to a later phase.
This entity records the minimal identity required by the peer-registration
architecture: a unique identifier and a unique email address.

Table: users
"""

import uuid

from sqlalchemy import String, text
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from coordinator.database.base import Base, TimestampMixin


class User(TimestampMixin, Base):
    """Platform user entity."""

    __tablename__ = "users"

    # Primary key — UUID generated by the database (gen_random_uuid on Postgres,
    # or hex() on SQLite in tests via the server_default text expression).
    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        server_default=text("(gen_random_uuid())"),
    )

    # Unique login / contact email.  NOT the authentication credential.
    email: Mapped[str] = mapped_column(
        String(320),  # RFC 5321 max email length
        unique=True,
        nullable=False,
        index=True,
    )

    # Human-readable display name — optional at registration.
    display_name: Mapped[str | None] = mapped_column(
        String(200),
        nullable=True,
    )

    # -------------------------------------------------------------------------
    # Relationships
    # -------------------------------------------------------------------------
    peers: Mapped[list["Peer"]] = relationship(  # type: ignore[name-defined]  # noqa: F821
        "Peer",
        back_populates="owner",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    jobs: Mapped[list["Job"]] = relationship(  # type: ignore[name-defined]  # noqa: F821
        "Job",
        back_populates="owner",
        cascade="all, delete-orphan",
        lazy="selectin",
    )

    def __repr__(self) -> str:
        return f"<User id={self.id} email={self.email!r}>"
